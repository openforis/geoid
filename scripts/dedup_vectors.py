#!/usr/bin/env python3
"""Golden vectors for the identity recipe (``geoid_geom_hash_v2``, recipe v2).

Recipe v2 (ADR-007, migration 0008) is engine-independent: an integer-lattice
canonicalization owned entirely by this repo, with a pure-Python reference
implementation (``geoid.domain.geometry_identity``) byte-identical to the SQL.
The corpus is therefore **generated by the Python reference, no database
involved** — and ``--check`` verifies that the *deployed* SQL function computes
the same digests, so its meaning is "deployed function ≡ Python reference":

    uv run python scripts/dedup_vectors.py --generate
    uv run python scripts/dedup_vectors.py --check [--dsn postgresql://...]

Vectors are **GeoJSON-keyed** (production's only geometry parse path is
``ST_GeomFromGeoJSON``, place_repo.py); a couple carry a paired ``wkt`` form to
pin WKT→GeoJSON convergence through the app codec. ``expect`` is ``"hash"`` (a
pinned sha256) or ``"error"`` (a lattice-degenerate geometry the recipe must
REJECT: SQLSTATE GD001 in SQL, ``DegenerateGeometryError`` in Python).

``--check`` needs a migrated database (it probes for ``geoid_geom_hash_v2`` and
tells you to run ``geoid migrate`` if absent) and also asserts the deployed
``geoid_geom_hash_default`` wrapper — the arbiter's actual entry point — matches
every digest. It is the post-deploy Cloud Run canary job and a bootstrap step.

``--generate`` recomputes the corpus from the reference and REFUSES to overwrite
a committed fixture whose digests differ, unless ``--force``: under v2, digest
drift can only mean the recipe *code* changed — a recipe-version event, never a
casual fix. The fixture is deterministic (no timestamps): regenerating on an
unchanged recipe is byte-identical.

Exit codes (CLI):
    0 ok · 1 step failed · 2 config/usage error · 3 identity digest drift
"""

