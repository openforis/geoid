REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURE_PATH = REPO_ROOT / "scripts" / "data" / "dedup_golden_vectors_v2.json"

RECIPE_VERSION = "v2"
SQLSTATE_DEGENERATE = "GD001"

# The deployed v2 function and the wrapper the arbiter CTE actually calls, fed
# through the SAME parse path production uses (ST_GeomFromGeoJSON).
CHECK_SQL_V2 = (
    "SELECT encode(geoid_geom_hash_v2(ST_SetSRID(ST_GeomFromGeoJSON(%(geojson)s), 4326)), 'hex')"
)
CHECK_SQL_WRAPPER = (
    "SELECT encode(geoid_geom_hash_default("
    "ST_SetSRID(ST_GeomFromGeoJSON(%(geojson)s), 4326)), 'hex')"
)
PROBE_SQL = "SELECT count(*) FROM pg_proc WHERE proname = 'geoid_geom_hash_v2'"

# run_sql(query, params) -> first column of the first row. Injected so the same
# logic runs over psycopg (bootstrap/CLI) or any other scalar-returning executor.
RunSQL = Callable[..., str]


class ConfigError(Exception):
    """Bad or missing configuration — exit 2, nothing was touched."""


class StepError(Exception):
    """A check/generate step failed — exit 1; the message carries remediation hints."""


