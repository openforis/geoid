@dataclass(frozen=True)
class VectorFailure:
    name: str
    expected: str
    actual: str


@dataclass(frozen=True)
class VectorReport:
    failures: tuple[VectorFailure, ...]
    passed: int


def reference_digest(geojson: dict) -> str:
    """The pure-Python reference digest (hex) for one geometry dict."""
    return geom_hash_v2(geojson).hex()


def load_fixture(path: Path = FIXTURE_PATH) -> dict:
    try:
        fixture = json.loads(path.read_text())
    except FileNotFoundError as exc:
        raise StepError(
            f"golden-vector fixture missing: {path}\n"
            "  Run from a synced checkout — scripts/data/ ships with the repo."
        ) from exc
    if fixture.get("recipe_version") != RECIPE_VERSION:
        raise StepError(
            f"fixture {path.name} carries recipe_version "
            f"{fixture.get('recipe_version')!r}, this script checks {RECIPE_VERSION!r}"
        )
    return fixture


def _sqlstate_of(exc: Exception) -> str | None:
    return getattr(exc, "sqlstate", None)


def check_vectors(run_sql: RunSQL, fixture: dict) -> VectorReport:
    """Recompute every pinned vector against the deployed SQL recipe.

    ``expect: hash`` vectors must match on BOTH ``geoid_geom_hash_v2`` and the
    ``geoid_geom_hash_default`` wrapper (proving the migration-0008 flip);
    ``expect: error`` vectors must raise SQLSTATE GD001.
    """
    failures: list[VectorFailure] = []
    passed = 0
    for vector in fixture["vectors"]:
        params = {"geojson": json.dumps(vector["geojson"])}
        if vector["expect"] == "error":
            try:
                actual = run_sql(CHECK_SQL_V2, params)
            except Exception as exc:  # noqa: BLE001 — classified by SQLSTATE below
                sqlstate = _sqlstate_of(exc)
                if sqlstate == SQLSTATE_DEGENERATE:
                    passed += 1
                else:
                    failures.append(
                        VectorFailure(
                            vector["name"],
                            f"SQLSTATE {SQLSTATE_DEGENERATE}",
                            f"SQLSTATE {sqlstate!r} ({exc})",
                        )
                    )
                continue
            failures.append(
                VectorFailure(vector["name"], f"SQLSTATE {SQLSTATE_DEGENERATE}", f"digest {actual}")
            )
            continue
        ok = True
        for label, query in (("geoid_geom_hash_v2", CHECK_SQL_V2), ("wrapper", CHECK_SQL_WRAPPER)):
            actual = run_sql(query, params)
            if actual != vector["sha256"]:
                failures.append(
                    VectorFailure(f"{vector['name']} [{label}]", vector["sha256"], actual)
                )
                ok = False
        if ok:
            passed += 1
    return VectorReport(tuple(failures), passed)


def ensure_v2_deployed(run_sql: RunSQL) -> None:
    """Fail with a clear hint when migration 0008 has not been applied yet."""
    if int(run_sql(PROBE_SQL)) < 1:
        raise StepError(
            "geoid_geom_hash_v2 is not deployed on this database — run `geoid migrate` "
            "(migration 0008) first; the v2 check validates the DEPLOYED function."
        )


def generate_fixture() -> dict:
    """Compute the corpus from the pure-Python reference (no database).

    Self-checks before returning: ``same_as`` pairs collapse, ``error`` cases
    raise ``DegenerateGeometryError``, and every paired ``wkt`` decodes (via the
    app's WKT codec) to a geometry with the identical digest.
    """
    digests: dict[str, str] = {}
    for case in VECTOR_CASES:
        if case.expect == "error":
            try:
                reference_digest(case.geojson)
            except DegenerateGeometryError:
                continue
            raise StepError(
                f"self-check failed: {case.name!r} should be rejected as lattice-"
                "degenerate but hashed — recipe or corpus bug; not writing the fixture"
            )
        digests[case.name] = reference_digest(case.geojson)
        if case.wkt is not None:
            converged = reference_digest(decode_geometry(case.wkt))
            if converged != digests[case.name]:
                raise StepError(
                    f"self-check failed: the WKT form of {case.name!r} does not "
                    "converge on the GeoJSON digest — codec or corpus bug"
                )
    for case in VECTOR_CASES:
        if case.same_as and digests[case.name] != digests[case.same_as]:
            raise StepError(
                f"self-check failed: {case.name!r} should canonicalize identically to "
                f"{case.same_as!r} but did not — recipe or corpus bug; not writing the fixture"
            )
    # Deterministic content (no timestamps): regenerating on an unchanged recipe
    # is byte-identical, which is itself a reproducibility check.
    return {
        "recipe_version": RECIPE_VERSION,
        "generated_by": (
            "scripts/dedup_vectors.py --generate — pure-Python reference "
            "(geoid.domain.geometry_identity), engine-independent (ADR-007)"
        ),
        "vectors": [
            {
                "name": case.name,
                "geojson": case.geojson,
                "wkt": case.wkt,
                "expect": case.expect,
                "sha256": digests.get(case.name),
                "same_as": case.same_as,
                "note": case.note,
            }
            for case in VECTOR_CASES
        ],
    }


def refuse_silent_regeneration(fixture: dict, out: Path, *, force: bool) -> None:
    """Refuse to overwrite a committed fixture whose digests differ (recipe-version
    event) unless ``--force``. A missing or same-digest fixture writes freely."""
    if force or not out.exists():
        return
    try:
        committed = json.loads(out.read_text())
    except (OSError, json.JSONDecodeError):
        return  # unreadable/corrupt committed file — overwriting it is the fix
    pinned = {v["name"]: v.get("sha256") for v in committed.get("vectors", [])}
    fresh = {v["name"]: v.get("sha256") for v in fixture["vectors"]}
    drifted = sorted(name for name in pinned.keys() & fresh.keys() if pinned[name] != fresh[name])
    if drifted:
        raise StepError(
            f"recomputed digests differ from the committed fixture for {drifted} — "
            "the recipe code changed. That is a RECIPE-VERSION EVENT (new migration, "
            "re-mint runbook), never a casual fix; pass --force only if that is intended."
        )


def _parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Check the deployed identity recipe against the golden-vector "
        "corpus, or (re)generate the corpus from the pure-Python reference."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="recompute the pinned vectors against the deployed geoid_geom_hash_v2",
    )
    parser.add_argument(
        "--generate",
        action="store_true",
        help="compute fresh digests from the Python reference and write the fixture "
        "(no database needed)",
    )
    parser.add_argument(
        "--dsn",
        default=None,
        help="libpq DSN/URL of the database for --check (default: GEOID_DATABASE_URL "
        "with any SQLAlchemy '+driver' suffix stripped — lets the Cloud Run canary "
        "job reuse the mounted asyncpg secret)",
    )
    parser.add_argument(
        "--fixture",
        type=Path,
        default=FIXTURE_PATH,
        help="fixture to check against (default: the committed corpus)",
    )
    parser.add_argument(
        "--out", type=Path, default=FIXTURE_PATH, help="where --generate writes the fixture"
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="allow --generate to overwrite a fixture whose digests differ "
        "(a recipe-version event)",
    )
    args = parser.parse_args(argv)
    if args.check == args.generate:
        raise ConfigError("pass exactly one of --check / --generate")
    if args.check and not args.dsn:
        args.dsn = _normalize_dsn(os.environ.get("GEOID_DATABASE_URL", ""))
        if not args.dsn:
            raise ConfigError("--check needs a database: pass --dsn or set GEOID_DATABASE_URL")
    return args


def _normalize_dsn(dsn: str) -> str:
    """Strip a SQLAlchemy driver suffix so psycopg/libpq accepts the URL.

    The deployed ``GEOID_DATABASE_URL`` is ``postgresql+asyncpg://…?host=/cloudsql/…``;
    psycopg wants plain ``postgresql://`` (the unix-socket ``?host=`` query form
    passes through to libpq untouched).
    """
    return re.sub(r"^postgresql\+\w+://", "postgresql://", dsn)


def _psycopg_run_sql(conn) -> RunSQL:
    def run_sql(query: str, params: dict | None = None) -> str:
        return conn.execute(query, params).fetchone()[0]

    return run_sql


def _run_check(args: argparse.Namespace) -> int:
    import psycopg

    try:
        with psycopg.connect(args.dsn, autocommit=True) as conn:
            run_sql = _psycopg_run_sql(conn)
            ensure_v2_deployed(run_sql)
            fixture = load_fixture(args.fixture)
            report = check_vectors(run_sql, fixture)
    except psycopg.Error as exc:
        print(f"✗ database error: {exc}")
        return 1
    for failure in report.failures:
        print(
            f"✗ vector {failure.name!r} drifted (expected {failure.expected}, got {failure.actual})"
        )
    print(f"{report.passed}/{len(fixture['vectors'])} vectors match")
    return 3 if report.failures else 0


def main(argv: list[str] | None = None) -> int:
    try:
        args = _parse_args(argv)
    except ConfigError as exc:
        print(f"✗ {exc}")
        return 2

    try:
        if args.generate:
            fixture = generate_fixture()
            refuse_silent_regeneration(fixture, args.out, force=args.force)
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(json.dumps(fixture, indent=2) + "\n")
            print(f"✓ wrote {len(fixture['vectors'])} vectors to {args.out}")
            print("  generated from the pure-Python reference (no engine dependence)")
            return 0
        return _run_check(args)
    except StepError as exc:
        print(f"✗ {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
